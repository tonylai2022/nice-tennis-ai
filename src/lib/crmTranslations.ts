export function translateCrmText(text: string, targetLang: 'en' | 'zh' = 'zh'): string {
    const trimmed = text.trim();
    if (!trimmed) return text;

    if (targetLang === 'zh') {
        const translated = translations[trimmed];
        if (translated) {
            return text.replace(trimmed, translated);
        }
        for (const { regex, replace } of patterns) {
            if (regex.test(trimmed)) {
                const replaced = trimmed.replace(regex, replace as any);
                return text.replace(trimmed, replaced);
            }
        }
        return text;
    }

    // targetLang === 'en'
    const english = zhToEn[trimmed];
    if (english) {
        return text.replace(trimmed, english);
    }
    for (const { regex, replace } of zhPatterns) {
        if (regex.test(trimmed)) {
            const replaced = trimmed.replace(regex, replace as any);
            return text.replace(trimmed, replaced);
        }
    }
    return text;
}

export function isCrmTranslatableAttribute(name: string): boolean {
    return name === 'placeholder' || name === 'aria-label' || name === 'title';
}
